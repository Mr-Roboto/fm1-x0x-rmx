"""Reduce pinned Mutable Instruments Grids nodes to sixteen sixteenth notes.

Only the 1,200-byte MAP is emitted. The original Euclidean table is test data.
"""
import argparse
import hashlib
from pathlib import Path
import re

SOURCE = Path(__file__).resolve().parents[1] / "assets/grids/resources.cc"
SOURCE_SHA256 = "02c4911d1ee940f921d50207c25a39d911c3f6af9ace87869e7e667954c63265"
LAYOUT = ((10, 8, 0, 9, 11), (15, 7, 13, 12, 6), (18, 14, 4, 5, 3),
          (23, 16, 21, 1, 2), (24, 19, 17, 20, 22))


def read_arrays(source=SOURCE):
    raw = Path(source).read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("Grids source differs from pinned eurorack 08460a6")
    arrays = {m.group(1): [int(v) for v in re.findall(r"\d+", m.group(2))]
              for m in re.finditer(r"const prog_uint(?:8|32)_t (\w+)\[\] PROGMEM = \{(.*?)\};",
                                   raw.decode(), re.S)}
    if any(len(arrays[f"node_{i}"]) != 96 for i in range(25)):
        raise ValueError("Grids requires 25 nodes of 3 x 32 values")
    return arrays


def reduce_nodes(arrays):
    return bytes(arrays[f"node_{node}"][channel * 32 + step * 2]
                 for row in LAYOUT for node in row
                 for channel in range(3) for step in range(16))


def generate(output):
    data = reduce_nodes(read_arrays())
    assert len(data) == 1200
    lines = ["/* SPDX-License-Identifier: GPL-3.0-or-later */",
             "/* Copyright 2012 Emilie Gillet. Reduced from Grids resources.cc,",
             " * eurorack 08460a69a7e1f7a81c5a2abcc7189c9a6b7208d4.",
             " * Generated by tools/gen_grids.py; spatial layout [x][y], even positions only. */",
             "#pragma once", "#include <stdint.h>",
             "static const uint8_t drum_gen_map[5][5][3][16] = {"]
    for x in range(5):
        lines.append("    {")
        for y in range(5):
            lines.append(f"        {{ /* node_{LAYOUT[x][y]} */")
            for channel in range(3):
                start = ((x * 5 + y) * 3 + channel) * 16
                lines.append("            {" + ", ".join(str(v) for v in data[start:start + 16]) + "},")
            lines.append("        },")
        lines.append("    },")
    lines.append("};")
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    generate(parser.parse_args().output)
