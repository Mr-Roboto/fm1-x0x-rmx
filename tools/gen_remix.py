"""Pack the canonical zero-based Remix rows; even slots occupy low nibbles."""
import argparse
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[1] / "assets/remix/remixes.txt"


def read_rows(path):
    rows = []
    for line in Path(path).read_text().splitlines():
        data = line.split("#", 1)[0].strip()
        if data:
            rows.append([int(value) for value in data.split()])
    if len(rows) != 256 or any(len(row) != 16 for row in rows):
        raise ValueError("Remix requires exactly 256 rows of 16 values")
    if any(value < 0 or value > 15 for row in rows for value in row):
        raise ValueError("Remix values must be in 0..15")
    if any(row[0] != 0 for row in rows):
        raise ValueError("Every Remix row must begin with zero")
    if rows[0] != list(range(16)):
        raise ValueError("A1 must be the identity mapping")
    return rows


def pack(rows):
    return bytes(row[i] | (row[i + 1] << 4)
                 for row in rows for i in range(0, 16, 2))


def generate(source, output):
    packed = pack(read_rows(source))
    assert len(packed) == 2048
    lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
             "/* Generated by tools/gen_remix.py; do not edit. Even slot: low nibble. */",
             "#pragma once", "#include <stdint.h>",
             "static const uint8_t remix_packed[2048] = {"]
    for i in range(0, len(packed), 8):
        lines.append("    " + ", ".join(f"0x{x:02x}" for x in packed[i:i + 8]) + ",")
    lines.append("};")
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generate(SOURCE, args.output)
